/**
 * Deterministic Mathematical Solver & Verification Layer for MPC Studio.
 * Handles modular arithmetic, Bézout identity, orders, cyclic groups,
 * matrix algebra, and finite group validation.
 */

export interface BezoutResult {
  gcd: number;
  x: number;
  y: number;
}

export class MathSolver {
  /**
   * Greatest Common Divisor (Euclidean algorithm)
   */
  static gcd(a: number, b: number): number {
    a = Math.abs(a);
    b = Math.abs(b);
    while (b !== 0) {
      const t = b;
      b = a % b;
      a = t;
    }
    return a;
  }

  /**
   * Extended Euclidean Algorithm: finds gcd, x, y such that ax + by = gcd(a, b)
   */
  static extendedGcd(a: number, b: number): BezoutResult {
    let x0 = 1, y0 = 0;
    let x1 = 0, y1 = 1;
    let r0 = Math.abs(a);
    let r1 = Math.abs(b);

    while (r1 !== 0) {
      const q = Math.floor(r0 / r1);
      const r2 = r0 - q * r1;
      const x2 = x0 - q * x1;
      const y2 = y0 - q * y1;

      r0 = r1;
      r1 = r2;
      x0 = x1;
      x1 = x2;
      y0 = y1;
      y1 = y2;
    }

    // Adjust signs if initial a or b was negative
    if (a < 0) x0 = -x0;
    if (b < 0) y0 = -y0;

    return { gcd: r0, x: x0, y: y0 };
  }

  /**
   * Modular inverse: returns u in [1, n-1] such that (a * u) = 1 [n], or null if gcd(a, n) != 1
   */
  static modularInverse(a: number, n: number): number | null {
    a = ((a % n) + n) % n;
    const { gcd, x } = this.extendedGcd(a, n);
    if (gcd !== 1) return null;
    return ((x % n) + n) % n;
  }

  /**
   * Modular exponentiation: computes (base^exp) mod n
   */
  static modularPower(base: number, exp: number, n: number): number {
    if (n === 1) return 0;
    base = ((base % n) + n) % n;
    let res = 1;
    while (exp > 0) {
      if (exp % 2 === 1) {
        res = (res * base) % n;
      }
      base = (base * base) % n;
      exp = Math.floor(exp / 2);
    }
    return res;
  }

  /**
   * Additive order of element a in (Z/nZ, +): n / gcd(a, n)
   */
  static orderAdditive(a: number, n: number): number {
    a = ((a % n) + n) % n;
    if (a === 0) return 1;
    return n / this.gcd(a, n);
  }

  /**
   * Multiplicative order of element a in (Z/nZ)*: smallest k >= 1 with a^k = 1 [n]
   */
  static orderMultiplicative(a: number, n: number): number | null {
    a = ((a % n) + n) % n;
    if (this.gcd(a, n) !== 1) return null; // Not invertible
    let current = a;
    let order = 1;
    while (current !== 1 && order <= n) {
      current = (current * a) % n;
      order++;
    }
    return current === 1 ? order : null;
  }

  /**
   * List of invertible elements in Z/nZ: (Z/nZ)*
   */
  static invertibleElements(n: number): number[] {
    const res: number[] = [];
    for (let i = 1; i < n; i++) {
      if (this.gcd(i, n) === 1) {
        res.push(i);
      }
    }
    return res;
  }

  /**
   * Euler's totient function phi(n)
   */
  static eulerTotient(n: number): number {
    return this.invertibleElements(n).length;
  }

  /**
   * Generate cyclic subgroup generated by an element in Z/nZ (either additive or multiplicative)
   */
  static cyclicSubgroup(a: number, n: number, multiplicative: boolean = false): number[] {
    const elements: number[] = [];
    if (multiplicative) {
      if (this.gcd(a, n) !== 1) return [a % n];
      let cur = 1;
      do {
        elements.push(cur);
        cur = (cur * a) % n;
      } while (cur !== 1 && elements.length < n);
    } else {
      let cur = 0;
      do {
        elements.push(cur);
        cur = (cur + a) % n;
      } while (cur !== 0 && elements.length < n);
    }
    return elements;
  }

  /**
   * 2x2 Matrix product: A * B
   */
  static matrix2x2Multiply(
    A: [[number, number], [number, number]],
    B: [[number, number], [number, number]]
  ): [[number, number], [number, number]] {
    return [
      [A[0][0] * B[0][0] + A[0][1] * B[1][0], A[0][0] * B[0][1] + A[0][1] * B[1][1]],
      [A[1][0] * B[0][0] + A[1][1] * B[1][0], A[1][0] * B[0][1] + A[1][1] * B[1][1]],
    ];
  }

  /**
   * 2x2 Matrix inverse
   */
  static matrix2x2Inverse(A: [[number, number], [number, number]]): [[number, number], [number, number]] | null {
    const det = A[0][0] * A[1][1] - A[0][1] * A[1][0];
    if (det === 0) return null;
    return [
      [A[1][1] / det, -A[0][1] / det],
      [-A[1][0] / det, A[0][0] / det],
    ];
  }

  /**
   * Heisenberg 3x3 Matrix product:
   * M(x, y, z) * M(x', y', z') = M(x+x', y+y', z+z'+xy')
   */
  static heisenbergProduct(
    m1: { x: number; y: number; z: number },
    m2: { x: number; y: number; z: number }
  ): { x: number; y: number; z: number } {
    return {
      x: m1.x + m2.x,
      y: m1.y + m2.y,
      z: m1.z + m2.z + m1.x * m2.y,
    };
  }

  /**
   * Heisenberg 3x3 Matrix inverse:
   * M(x, y, z)^(-1) = M(-x, -y, -z + xy)
   */
  static heisenbergInverse(m: { x: number; y: number; z: number }): { x: number; y: number; z: number } {
    return {
      x: -m.x,
      y: -m.y,
      z: -m.z + m.x * m.y,
    };
  }

  /**
   * Verifies Cayley Table for finite group
   */
  static verifyGroupTable(elements: string[], table: Record<string, Record<string, string>>): {
    isClosure: boolean;
    neutralElement: string | null;
    hasInverses: boolean;
    isAssociative: boolean;
    isAbelian: boolean;
  } {
    const set = new Set(elements);
    let isClosure = true;
    let isAbelian = true;

    // Check closure and commutativity
    for (const a of elements) {
      for (const b of elements) {
        const prod = table[a]?.[b];
        if (!set.has(prod)) isClosure = false;
        if (table[a]?.[b] !== table[b]?.[a]) isAbelian = false;
      }
    }

    // Find neutral element
    let neutralElement: string | null = null;
    for (const e of elements) {
      let isNeutral = true;
      for (const a of elements) {
        if (table[e]?.[a] !== a || table[a]?.[e] !== a) {
          isNeutral = false;
          break;
        }
      }
      if (isNeutral) {
        neutralElement = e;
        break;
      }
    }

    // Check inverses if neutral element exists
    let hasInverses = !!neutralElement;
    if (neutralElement) {
      for (const a of elements) {
        let hasInv = false;
        for (const b of elements) {
          if (table[a]?.[b] === neutralElement && table[b]?.[a] === neutralElement) {
            hasInv = true;
            break;
          }
        }
        if (!hasInv) {
          hasInverses = false;
          break;
        }
      }
    }

    // Check associativity: (a*b)*c == a*(b*c)
    let isAssociative = true;
    for (const a of elements) {
      for (const b of elements) {
        for (const c of elements) {
          const ab = table[a]?.[b];
          const bc = table[b]?.[c];
          if (!ab || !bc || table[ab]?.[c] !== table[a]?.[bc]) {
            isAssociative = false;
            break;
          }
        }
        if (!isAssociative) break;
      }
      if (!isAssociative) break;
    }

    return {
      isClosure,
      neutralElement,
      hasInverses,
      isAssociative,
      isAbelian,
    };
  }
}
